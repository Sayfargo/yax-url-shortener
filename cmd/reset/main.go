type (
	templateReset struct {
		// Package is the current package name.
		Package string
		// RStructs contains all structs with the 'generate:reset' tag.
		RStructs []resettableStruct
	}
	resettableStruct struct {
		// StructName is the name of the structure.
		StructName string
		// Receiver is used for the generated method in the template.
		// It is the first letter of StructName.
		Receiver string
		// Fields contains more information about the structure fields.
		Fields []fieldData
	}
	fieldData struct {
		// Name is the name of the structure field.
		Name string
		// Kind is the short name of the field type.
		// For example, complex types like map or slice have the kind "map" or "slice".
		// For a simple variable or selector (like time.Time), it is "other".
		Kind string
		// TypeName is the underlying type representation without a leading pointer asterisk
		// (e.g., "int", "time.Time", or "[10]byte"). Used to allocate zero values via new().
		TypeName string
		// IsPointer indicates whether the field is declared as a pointer type.
		IsPointer bool
	}
)

const Template = `
	// Code generated by go generate; DO NOT EDIT.
	// This file was generated by genreset.go

	package {{.Package}}

	{{range .RStructs}}
	func ({{.Receiver}} *{{.StructName}}) Reset() {
		if {{.Receiver}} == nil {
			return
		}
		{{$recv := .Receiver}}
		{{range .Fields}}
		{{if eq .Kind "slice"}}
		{{if .IsPointer}}
		if {{$recv}}.{{.Name}} != nil {
			*{{$recv}}.{{.Name}} = (*{{$recv}}.{{.Name}})[:0] 
		} 
		{{else}}
		{{$recv}}.{{.Name}} = {{$recv}}.{{.Name}}[:0] 
		{{end}}

		{{else if eq .Kind "array"}} 
		{{if .IsPointer}}
		if {{$recv}}.{{.Name}} != nil {
			*{{$recv}}.{{.Name}} = *new({{.TypeName}})
		}
		{{else}}
		{{$recv}}.{{.Name}} = *new({{.TypeName}})
		{{end}}

		{{else if eq .Kind "map"}}
		{{if .IsPointer}}
		if {{$recv}}.{{.Name}} != nil {
			clear(*{{$recv}}.{{.Name}})
		}
		{{else}}
		clear({{$recv}}.{{.Name}})
		{{end}}
	
		{{else if eq .Kind "other"}}
		{{if .IsPointer}}
		if {{$recv}}.{{.Name}} != nil {
			if resetter, ok := any({{$recv}}.{{.Name}}).(interface{ Reset() }); ok {
				resetter.Reset()
			} else {
				*{{$recv}}.{{.Name}} = *new({{.TypeName}})
			}
		}
		{{else}}
		if resetter, ok := any(&{{$recv}}.{{.Name}}).(interface{ Reset() }); ok {
			resetter.Reset()
		} else {
			{{$recv}}.{{.Name}} = *new({{.TypeName}}) 
		}
		{{end}}

		{{end}}
		{{end}}
	}
	{{end}}
`

var tmpl = template.Must(template.New("reset").Parse(Template))

func main() {

	var (
		root = "."
		dirs string
	)

	flag.StringVar(
		&dirs,
		"i",
		"",
		"Ignored directories",
	)

	flag.Parse()

	ignoredDirs := strings.Fields(dirs)

	if err := process(root, ignoredDirs...); err != nil {
		log.Printf("process failed: %v", err)
	}

}

func process(dir string, ignoredDirs ...string) error {
	// читаем все древо директорий из текущего корня
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("os read dir: %w", err)
	}

	var (
		// заранее распаршенные в AST файлы для удобного анализа всех файлов текущий директории (пакета)
		files []*ast.File
		// поддиректории для рекурсивного обхода
		subDirs []string
		fset    = token.NewFileSet()
	)

	for _, entry := range entries {
		fullPath := filepath.Join(dir, entry.Name())
		if entry.IsDir() {
			// игнорируем директории, которые были указаны через флаг
			if len(ignoredDirs) > 0 {
				if slices.Contains(ignoredDirs, entry.Name()) {
					continue
				}
			}
			subDirs = append(subDirs, fullPath)
			// сгенерированные и файлы с тестами игнорируем
		} else if strings.HasSuffix(entry.Name(), ".go") &&
			!strings.HasSuffix(entry.Name(), ".gen.go") &&
			!strings.HasSuffix(entry.Name(), "_test.go") {
			f, err := parser.ParseFile(fset, fullPath, nil, parser.ParseComments)
			if err != nil {
				log.Printf("parse file: %v path: %s", err, fullPath)
				continue
			}
			files = append(files, f)
		}
	}

	if len(files) > 0 {
		log.Printf("Start inspect files in dir %s", dir)
		var resetStructs = []resettableStruct{}

		for _, file := range files {
			resetStructs = append(resetStructs, findResetStructs(fset, file)...)
		}

		if len(resetStructs) > 0 {
			var b bytes.Buffer
			if err := tmpl.Execute(&b, templateReset{
				Package:  files[0].Name.Name,
				RStructs: resetStructs,
			}); err != nil {
				return fmt.Errorf("template execute: %w", err)
			}

			data, err := format.Source(b.Bytes())
			if err != nil {
				return fmt.Errorf("format source: %w", err)
			}
			// включаем импорты в сгенерированный файл если в структуре будут объекты селекторы (из других пакетов)
			result, err := imports.Process("", data, nil)
			if err != nil {
				return fmt.Errorf("imports process: %w", err)
			}

			// dirName := filepath.Base(dir)

			// if dirName == "." || dirName == string(filepath.Separator) {
			// 	dirName = files[0].Name.Name
			// }

			// baseName := fmt.Sprintf("%s.gen.go", dirName)
			outPath := filepath.Join(dir, "reset.gen.go")
			err = os.WriteFile(outPath, result, 0644)
			if err != nil {
				return fmt.Errorf("os write file: %w", err)
			}
		}

	}

	for _, subDir := range subDirs {
		// рекурсивный обход
		if err := process(subDir, ignoredDirs...); err != nil {
			log.Printf("sub dir err: %v", err)
		}
	}
	return nil
}

func findResetStructs(fset *token.FileSet, file *ast.File) []resettableStruct {

	var rss = []resettableStruct{}

	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		// проверяем есть ли нужный тэг в gd.Doc
		gdHasComment := hasTargetComment(gd.Doc, "generate:reset")

		for _, spc := range gd.Specs {
			ts, ok := spc.(*ast.TypeSpec)
			if !ok {
				continue
			}
			// если не было и в gd.Doc и в ts.Doc продолжаем обход
			if !gdHasComment && !hasTargetComment(ts.Doc, "generate:reset") {
				continue
			}

			structT, ok := ts.Type.(*ast.StructType)
			if !ok {
				continue
			}

			log.Printf("struct found: %s\n", ts.Name.Name)

			var (
				rs  resettableStruct
				fds = []fieldData{}
			)

			rs.StructName = ts.Name.Name
			// получение имени для ресивера метода
			rs.Receiver = getReceiverName(ts.Name.Name)

			for _, field := range structT.Fields.List {
				// получаем информацию о поле структуры
				typeName, kind, isPointer, err := extractExpr(fset, field.Type)
				if err != nil {
					log.Printf("extraxt expr err: %v", err)
				}

				if len(field.Names) == 0 {
					parts := strings.Split(typeName, ".")
					embeddedName := parts[len(parts)-1]
					fds = append(fds, fieldData{
						Name:      embeddedName,
						TypeName:  typeName,
						Kind:      kind,
						IsPointer: isPointer,
					})
					continue
				}

				for _, name := range field.Names {
					fds = append(fds, fieldData{
						Name:      name.Name,
						TypeName:  typeName,
						Kind:      kind,
						IsPointer: isPointer,
					})
				}
			}

			if len(fds) < 1 {
				continue
			}

			rs.Fields = fds
			rss = append(rss, rs)
		}
	}

	return rss
}

func extractExpr(fset *token.FileSet, expr ast.Expr) (typeName, kind string, isPointer bool, err error) {
	var b bytes.Buffer
	// приводим к указателю и если это указатель, ставим isPointer в true
	if star, ok := expr.(*ast.StarExpr); ok {
		isPointer = true
		// перезатираем оригинальный expr в то, что стоит справа от `*`
		expr = star.X
	}

	if err := format.Node(&b, fset, expr); err != nil {
		return "", "", false, fmt.Errorf("formats node err: %w, position: %s", err, fset.Position(expr.Pos()))
	}
	typeName = b.String()
	switch t := expr.(type) {
	case *ast.ArrayType:
		if t.Len == nil {
			kind = "slice"
		} else {
			kind = "array"
		}
	case *ast.MapType:
		kind = "map"
	default:
		kind = "other"
	}

	return
}

func hasTargetComment(doc *ast.CommentGroup, target string) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if text == target {
			return true
		}
	}
	return false
}

func getReceiverName(structName string) string {
	return strings.ToLower(string([]rune(structName)[0]))
}
