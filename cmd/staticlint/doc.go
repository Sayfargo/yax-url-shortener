// Staticlint — инструмент статического анализа кода на базе multichecker
// из пакета golang.org/x/tools/go/analysis/multichecker.
//
// # Механизм запуска multichecker
//
// Функция multichecker.Main принимает срез экземпляров *analysis.Analyzer и
// формирует полноценную CLI-утилиту со стандартным интерфейсом флагов (аналогичным
// go vet).
//
// Запуск проверки всех пакетов проекта из корня репозитория:
//
//	go run ./cmd/staticlint ./...
//
// Сборка бинарного файла и запуск с флагами:
//
//	go build -o bin/staticlint ./cmd/staticlint
//	./bin/staticlint -help
//	./bin/staticlint ./...
//
// # Подключённые анализаторы
//
// Стандартные анализаторы из golang.org/x/tools/go/analysis/passes:
//   - waitgroup — определяет анализатор, который обнаруживает простые ошибки использования sync.WaitGroup.
//   - slog — определяет анализатор, который проверяет наличие несовпадающих пар ключ-значение в вызовах log/slog.
//   - tests — определяет анализатор, который проверяет функции Test, Benchmark, Fuzzing и
//     Example на наличие некорректных имен, неправильных сигнатур и примеров,
//     документирующих несуществующие идентификаторы.
//
// Анализаторы из пакета honnef.co/go/tools:
//
//   - Класс SA (staticcheck) — все анализаторы категории SA, которые
//     касаются неправильного использования стандартной библиотеки.
//     Как правило, это связано с некорректными аргументами функций
//     или нарушением других инвариантов, изложенных в документации стандартной библиотеки.
//
//   - S1000 (simple) — предлагает заменить конструкцию select с единственным
//     блоком case на прямое чтение или запись в канал.
//
//   - S1028 (simple) — упрощает комбинацию errors.New(fmt.Sprintf(...)) до
//     вызова fmt.Errorf(...).
//
//   - ST1005 (stylecheck) — проверяет форматирование строк ошибок (строки не должны
//     начинаться с заглавной буквы и заканчиваться точкой).
//
//   - ST1012 (stylecheck) — следит за тем, чтобы имена экспортируемых переменных
//     ошибок начинались с префикса Err.
//
//   - QF1003 (quickfix) — предлагает заменить длинные цепочки if/else if на
//     конструкцию switch для повышения читаемости.
//
// Собственные анализаторы:
//   - noosexist — запрещает прямой вызов os.Exit внутри функции main пакета main,
//     чтобы обеспечить корректное завершение работы приложения.
